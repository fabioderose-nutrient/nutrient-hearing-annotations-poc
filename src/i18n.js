const requested = new URLSearchParams(location.search).get("lang") || import.meta.env.VITE_DEFAULT_LANG;
export const lang = requested in strings ? requested : "en";
export const t = strings[lang];

export function applyStaticStrings(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t[el.dataset.i18n] ?? el.dataset.i18n));
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => (el.placeholder = t[el.dataset.i18nPlaceholder]));
  root.querySelectorAll("[data-tip-key]").forEach((el) => (el.dataset.tip = t[el.dataset.tipKey]));
}
